const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('petAPI', {
  startDrag: () => ipcRenderer.send('start-drag'),
  endDrag: () => ipcRenderer.send('end-drag'),
  moveWindow: (x, y) => ipcRenderer.send('move-window', { x, y }),
  showContextMenu: (pos) => ipcRenderer.send('show-context-menu', pos),
  openPhrasesEditor: () => ipcRenderer.send('open-phrases-editor'),
  openShortcutsEditor: () => ipcRenderer.send('open-shortcuts-editor'),
  getPhrases: () => ipcRenderer.invoke('get-phrases'),
  savePhrases: (list) => ipcRenderer.invoke('save-phrases', list),
  getShortcuts: () => ipcRenderer.invoke('get-shortcuts'),
  saveShortcuts: (list) => ipcRenderer.invoke('save-shortcuts', list),
  addScore: (amount) => ipcRenderer.send('add-score', amount),
  getScore: () => ipcRenderer.invoke('get-score'),
  getShopData: () => ipcRenderer.invoke('get-shop-data'),
  buyQuantity: () => ipcRenderer.invoke('buy-quantity'),
  buyValue: () => ipcRenderer.invoke('buy-value'),
  buyAutoChase: () => ipcRenderer.invoke('buy-auto-chase'),
  buySpeed: () => ipcRenderer.invoke('buy-speed'),
  buyDash: () => ipcRenderer.invoke('buy-dash'),
  resetAll: () => ipcRenderer.invoke('reset-all'),
  onSetMode: (cb) => ipcRenderer.on('set-mode', (_e, mode) => cb(mode)),
  onSetMenuOpen: (cb) => ipcRenderer.on('set-menu-open', (_e, open) => cb(open)),
  onPhrasesUpdated: (cb) => ipcRenderer.on('phrases-updated', (_e, list) => cb(list)),
  onFlash: (cb) => ipcRenderer.on('flash', () => cb()),
  onCrazyStart: (cb) => ipcRenderer.on('crazy-start', (_e, duration) => cb(duration)),
  onFoodStart: (cb) => ipcRenderer.on('food-start', (_e, config) => cb(config)),
  onPetPositions: (cb) => ipcRenderer.on('pet-positions', (_e, positions) => cb(positions)),
  onFoodPositions: (cb) => ipcRenderer.on('food-positions', (_e, positions) => cb(positions)),
  onSetAutoChase: (cb) => ipcRenderer.on('set-auto-chase', (_e, enabled) => cb(enabled)),
  onSetChaseDuration: (cb) => ipcRenderer.on('set-chase-duration', (_e, d) => cb(d)),
  onSetDash: (cb) => ipcRenderer.on('set-dash', (_e, cfg) => cb(cfg)),
  dashStarted: (info) => ipcRenderer.send('dash-started', info),
  onDashSweep: (cb) => ipcRenderer.on('dash-sweep', (_e, info) => cb(info)),
  foodExploded: (info) => ipcRenderer.send('food-exploded', info),
  onDrawDashTrail: (cb) => ipcRenderer.on('draw-dash-trail', (_e, info) => cb(info)),
  onSpawnFoodParticles: (cb) => ipcRenderer.on('spawn-food-particles', (_e, info) => cb(info)),
  sendFoodPositions: (list) => ipcRenderer.send('food-positions', list),
  foodDone: () => ipcRenderer.send('food-done'),
  getWindowPos: () => ipcRenderer.invoke('get-window-pos'),
  getScreenSize: () => ipcRenderer.invoke('get-screen-size'),
  getPetSize: () => ipcRenderer.invoke('get-pet-size'),
  onMenuItems: (cb) => ipcRenderer.on('menu-items', (_e, items) => cb(items)),
  menuClick: (id) => ipcRenderer.send('menu-click', id),
  menuClose: () => ipcRenderer.send('menu-close')
})